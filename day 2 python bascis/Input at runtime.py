# The process of converting one data type into another is called Type Casting (or Type Conversion).
'''
Converting a value from one data type to another is called type casting or type conversion.
In Python, functions like int(), float(), and str() are used for explicit type casting.
In the example, int(num1) converts the string input into an integer before performing addition.
'''
num1=int(input("Enter first number"))
num2=int(input("Enter second number"))
print(num1+num2)  #4550 input will take as string

print(int(num1)+int(num2))


